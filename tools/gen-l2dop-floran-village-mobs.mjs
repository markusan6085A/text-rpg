/**
 * Генерує src/data/world/l2dop/floranVillageMobs.generated.ts — моби L2 рівнів 10–36 (Floran Village).
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

const MOB_DIR = path.join(root, "tools", "htmlскіли", "моби!");
const LEVEL_MIN = 10;
const LEVEL_MAX = 36;

function parseNpcBlocks(text) {
  const out = new Map();
  const re = /<npc\s+id="(\d+)"\s+name="([^"]*)"[^>]*>([\s\S]*?)<\/npc>/g;
  let m;
  while ((m = re.exec(text)) !== null) {
    out.set(Number(m[1]), { name: m[2], body: m[3] });
  }
  return out;
}

function getSet(body, key) {
  const r = new RegExp(`<set\\s+name="${key}"\\s+val="([^"]*)"`, "i");
  const m = body.match(r);
  return m ? m[1] : null;
}

function parseAdenaRange(body) {
  const dm = body.match(/<drops>([\s\S]*?)<\/drops>/);
  if (!dm) return { adenaMin: 100, adenaMax: 500 };
  const cat0 = dm[1].match(/<category\s+id="0">([\s\S]*?)<\/category>/);
  if (!cat0) return { adenaMin: 100, adenaMax: 500 };
  const adenaDrop = cat0[1].match(/<drop\s+itemid="57"\s+min="(\d+)"\s+max="(\d+)"/);
  if (!adenaDrop) return { adenaMin: 100, adenaMax: 500 };
  return { adenaMin: Number(adenaDrop[1]), adenaMax: Number(adenaDrop[2]) };
}

function roundNum(v) {
  const n = Number(String(v).replace(/,/g, ""));
  return Number.isFinite(n) ? Math.round(n) : 0;
}

function main() {
  const files = fs.readdirSync(MOB_DIR).filter((f) => f.endsWith(".xml"));
  const all = new Map();
  for (const f of files) {
    const fp = path.join(MOB_DIR, f);
    const text = fs.readFileSync(fp, "utf8");
    for (const [id, rec] of parseNpcBlocks(text)) {
      all.set(id, rec);
    }
  }

  const mobs = [];
  const levels = [];
  for (const [npcId, rec] of all) {
    const { name, body } = rec;
    const typ = getSet(body, "type");
    const exp = roundNum(getSet(body, "exp") ?? "0");
    if (typ !== "Monster" || exp <= 0) continue;
    const level = roundNum(getSet(body, "level") ?? "1");
    if (level < LEVEL_MIN || level > LEVEL_MAX) continue;
    const hp = roundNum(getSet(body, "hp") ?? "100");
    const mp = roundNum(getSet(body, "mp") ?? "0");
    const pAtk = roundNum(getSet(body, "pAtk") ?? "10");
    const pDef = roundNum(getSet(body, "pDef") ?? "10");
    const mAtk = roundNum(getSet(body, "mAtk") ?? "0");
    const mDef = roundNum(getSet(body, "mDef") ?? "10");
    const sp = roundNum(getSet(body, "sp") ?? String(level * 2));
    const { adenaMin, adenaMax } = parseAdenaRange(body);
    levels.push(level);
    mobs.push({
      id: `l2dop_${npcId}`,
      name,
      level,
      hp,
      mp,
      pAtk,
      mAtk,
      pDef,
      mDef,
      exp,
      sp,
      adenaMin,
      adenaMax,
    });
  }

  mobs.sort((a, b) => a.level - b.level || Number(a.id.replace("l2dop_", "")) - Number(b.id.replace("l2dop_", "")));

  levels.sort((a, b) => a - b);
  console.log("Floran Village pool:", mobs.length, "level", levels[0], "..", levels[levels.length - 1]);

  const lines = mobs.map(
    (m) => `  {
    id: "${m.id}",
    name: ${JSON.stringify(m.name)},
    level: ${m.level},
    hp: ${m.hp},
    mp: ${m.mp},
    pAtk: ${m.pAtk},
    mAtk: ${m.mAtk},
    pDef: ${m.pDef},
    mDef: ${m.mDef},
    exp: ${m.exp},
    sp: ${m.sp},
    adenaMin: ${m.adenaMin},
    adenaMax: ${m.adenaMax},
    dropChance: 0.7,
    drops: [],
    spoil: [],
  }`
  );

  const outPath = path.join(root, "src", "data", "world", "l2dop", "floranVillageMobs.generated.ts");
  const header = `// AUTO-GENERATED by tools/gen-l2dop-floran-village-mobs.mjs — do not edit by hand.
import type { Mob } from "../types";

export const L2DOP_FLORAN_VILLAGE_POOL: Mob[] = [
`;
  const footer = `];
`;
  fs.writeFileSync(outPath, `${header}${lines.join(",\n")}\n${footer}`, "utf8");
  console.log("Wrote", outPath);
}

main();
