/**
 * Генерує src/data/world/l2dop/goddardMobs.generated.ts з L2 XML (Monster, exp>0).
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

function range(a, b) {
  const o = [];
  for (let i = a; i <= b; i++) o.push(i);
  return o;
}

const GODDARD_NPC_IDS = [
  ...range(21314, 21323),
  ...range(21324, 21342),
  ...range(21350, 21373),
  ...range(22122, 22129),
];

const MOB_XML_FILES = [
  path.join(root, "tools", "htmlскіли", "моби!", "21000-21999.xml"),
  path.join(root, "tools", "htmlскіли", "моби!", "22000-22999.xml"),
];

function parseNpcBlocks(text) {
  const out = new Map();
  const re = /<npc\s+id="(\d+)"\s+name="([^"]*)"[^>]*>([\s\S]*?)<\/npc>/g;
  let m;
  while ((m = re.exec(text)) !== null) {
    out.set(Number(m[1]), { name: m[2], body: m[3] });
  }
  return out;
}

function getSet(body, key) {
  const r = new RegExp(`<set\\s+name="${key}"\\s+val="([^"]*)"`, "i");
  const m = body.match(r);
  return m ? m[1] : null;
}

function parseAdenaRange(body) {
  const dm = body.match(/<drops>([\s\S]*?)<\/drops>/);
  if (!dm) return { adenaMin: 100, adenaMax: 500 };
  const cat0 = dm[1].match(/<category\s+id="0">([\s\S]*?)<\/category>/);
  if (!cat0) return { adenaMin: 100, adenaMax: 500 };
  const adenaDrop = cat0[1].match(/<drop\s+itemid="57"\s+min="(\d+)"\s+max="(\d+)"/);
  if (!adenaDrop) return { adenaMin: 100, adenaMax: 500 };
  return { adenaMin: Number(adenaDrop[1]), adenaMax: Number(adenaDrop[2]) };
}

function roundNum(v) {
  const n = Number(String(v).replace(/,/g, ""));
  return Number.isFinite(n) ? Math.round(n) : 0;
}

function main() {
  let all = new Map();
  for (const f of MOB_XML_FILES) {
    if (!fs.existsSync(f)) {
      console.warn("missing", f);
      continue;
    }
    const text = fs.readFileSync(f, "utf8");
    for (const [id, rec] of parseNpcBlocks(text)) {
      all.set(id, rec);
    }
  }

  const mobs = [];
  const levels = [];
  for (const npcId of GODDARD_NPC_IDS) {
    const rec = all.get(npcId);
    if (!rec) {
      console.warn("NPC not found:", npcId);
      continue;
    }
    const { name, body } = rec;
    const typ = getSet(body, "type");
    const exp = roundNum(getSet(body, "exp") ?? "0");
    if (typ !== "Monster" || exp <= 0) {
      console.warn("skip (not monster or no exp):", npcId, name, typ, exp);
      continue;
    }
    const level = roundNum(getSet(body, "level") ?? "1");
    const hp = roundNum(getSet(body, "hp") ?? "100");
    const mp = roundNum(getSet(body, "mp") ?? "0");
    const pAtk = roundNum(getSet(body, "pAtk") ?? "10");
    const pDef = roundNum(getSet(body, "pDef") ?? "10");
    const mAtk = roundNum(getSet(body, "mAtk") ?? "0");
    const mDef = roundNum(getSet(body, "mDef") ?? "10");
    const sp = roundNum(getSet(body, "sp") ?? String(level * 2));
    const { adenaMin, adenaMax } = parseAdenaRange(body);
    levels.push(level);
    mobs.push({
      id: `l2dop_${npcId}`,
      name,
      level,
      hp,
      mp,
      pAtk,
      mAtk,
      pDef,
      mDef,
      exp,
      sp,
      adenaMin,
      adenaMax,
    });
  }

  levels.sort((a, b) => a - b);
  console.log("Goddard mobs:", mobs.length, "level min", levels[0], "max", levels[levels.length - 1]);

  const lines = mobs.map(
    (m) => `  {
    id: "${m.id}",
    name: ${JSON.stringify(m.name)},
    level: ${m.level},
    hp: ${m.hp},
    mp: ${m.mp},
    pAtk: ${m.pAtk},
    mAtk: ${m.mAtk},
    pDef: ${m.pDef},
    mDef: ${m.mDef},
    exp: ${m.exp},
    sp: ${m.sp},
    adenaMin: ${m.adenaMin},
    adenaMax: ${m.adenaMax},
    dropChance: 0.7,
    drops: [],
    spoil: [],
  }`
  );

  const outPath = path.join(root, "src", "data", "world", "l2dop", "goddardMobs.generated.ts");
  const header = `// AUTO-GENERATED by tools/gen-l2dop-goddard-mobs.mjs — do not edit by hand.
import type { Mob } from "../types";

export const L2DOP_GODDARD_POOL: Mob[] = [
`;
  const footer = `];
`;
  fs.writeFileSync(outPath, `${header}${lines.join(",\n")}\n${footer}`, "utf8");
  console.log("Wrote", outPath);
}

main();
