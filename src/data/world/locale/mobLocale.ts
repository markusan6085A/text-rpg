function hasCyrillic(s: string): boolean {
  return /[а-яА-ЯіІїЇєЄґҐёЁыЭъЪ]/.test(s);
}

function mostlyEnglishLetters(s: string): boolean {
  const letters = s.replace(/[^a-zA-Zа-яА-ЯіІїЇєЄґҐёЁ]/g, "");
  if (!letters.length) return false;
  const lat = (letters.match(/[a-zA-Z]/g) || []).length;
  return lat / letters.length > 0.55;
}

function translateEnglishToRu(s: string): string {
  let acc = s;
  for (const [en, ru] of EN_TO_RU) {
    acc = acc.replace(new RegExp(escapeRe(en), "gi"), ru);
  }
  return acc;
}

function ruMobToUk(s: string): string {
  return applyPairs(s, RU_TO_UK_MOB);
}

function localizeChampionTag(lang: Language): string {
  return lang === "uk" ? `${CHAMP_UK} ` : `${CHAMP_RU} `;
}

function stripChampion(name: string): { rest: string; had: boolean } {
  if (name.startsWith(CHAMP_EN)) return { rest: name.slice(CHAMP_EN.length).trimStart(), had: true };
  if (name.startsWith(CHAMP_RU)) return { rest: name.slice(CHAMP_RU.length).trimStart(), had: true };
  if (name.startsWith(CHAMP_UK)) return { rest: name.slice(CHAMP_UK.length).trimStart(), had: true };
  return { rest: name, had: false };
}

function localizeBody(body: string, lang: Language): string {
  const t = body.trim();
  if (!t) return body;
  if (mostlyEnglishLetters(t)) {
    const ru = translateEnglishToRu(t);
    return lang === "ru" ? ru : ruMobToUk(ru);
  }
  if (!hasCyrillic(t)) return t;
  if (lang === "ru") {
    return applyPairs(t, CYR_UK_TO_RU);
  }
  if (lang === "uk" && /[ыэёъЁЫЭЪ]/.test(t)) {
    return applyPairs(t, CYR_RU_TO_UK);
  }
  return t;
}

export function localizeMobDisplayName(name: string, lang: Language): string {
  const raw = String(name ?? "");
  const { rest, had: hadChamp } = stripChampion(raw);
  let body = rest;
  let raidPrefix = "";
  if (RAID_EN.test(body)) {
    body = body.replace(RAID_EN, "");
    raidPrefix = lang === "uk" ? RAID_UK : RAID_RU;
  }
  const localizedBody = localizeBody(body, lang);
  const champPrefix = hadChamp ? localizeChampionTag(lang) : "";
  return `${champPrefix}${raidPrefix}${localizedBody}`;
}
