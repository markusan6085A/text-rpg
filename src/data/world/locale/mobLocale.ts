function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function applyPairs(s: string, pairs: readonly (readonly [string, string])[]): string {
  let out = s;
  for (const [from, to] of pairs) {
    out = out.replace(new RegExp(escapeRe(from), "gi"), to);
  }
  return out;
}

