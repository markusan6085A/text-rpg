/** Підмішує M.Def / maxMp у записи магазинної біжутерії (джерело: l2elo Interlude). */
export function applyShopJewelryStatsToItemsDB(
  db: Record<string, ItemDefinition>
): Record<string, ItemDefinition> {
  const out: Record<string, ItemDefinition> = { ...db };
  for (const [id, j] of Object.entries(SHOP_JEWELRY_STATS)) {
    const def = out[id];
    if (!def) continue;
    out[id] = {
      ...def,
      stats: {
        ...(def.stats || {}),
        mDef: j.mDef,
        ...(j.maxMp != null && j.maxMp > 0 ? { maxMp: j.maxMp } : {}),
      },
    };
  }
  return out;
}
